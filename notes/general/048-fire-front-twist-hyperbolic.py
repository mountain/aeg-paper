#!/usr/bin/env python3
"""
048 — Hyperbolic fire-front twist: the thrice-punctured sphere M = H^2 / Γ(2).

Ports the flat-torus fire-front analysis (047) to a torsion-free Fuchsian group.
Here M is the thrice-punctured sphere (cusped pair of pants), realized as the
quotient of the upper half-plane H = {Im z > 0} by the principal congruence
subgroup of level two

    Γ(2) = { [[a,b],[c,d]] ∈ SL(2,Z) : a,d odd, b,c even } / {±I},

freely generated by the two parabolics (classical)

    A : z -> z + 2,      B : z -> z / (2z + 1),

with three cusps at {0, 1, ∞}.  Basepoint p = i.

Fire front: in the cover the wavefront Σ_t = {d(p, x) = t} is a hyperbolic circle
(Euclidean circle center Im(p)·cosh t + i·Im(p)·sinh t ... see circle_at).  On the
quotient the distance circle is C_t = π(Σ_t).  Its self-intersections are governed
by the exact same mechanism as the flat torus:

  * a crossing is born at time t = ||γ||/2 = d(p, γp)/2  for γ ∈ Γ(2) \\ {e};
  * each unoriented {γ, γ⁻¹} gives two transverse crossings (the two intersection
    points of the hyperbolic circles Σ_t(p) and Σ_t(γ⁻¹p));
  * hence N(t) = #{ γ ∈ Γ(2) \\ {e} : d(p, γp) < 2t }, an orbit-counting function
    that grows exponentially in t (Patterson/Margulis; critical exponent δ = 1).

STATUS: the event-time formula and N(t) = orbit count are PROVED (same chord /
distance-sphere argument as 047, now for any discrete group).  The concrete
enumeration below is a COMPUTATIONALLY VERIFIED EXAMPLE: reduced words in A, B are
enumerated to depth D (default 12), words with displacement ≤ UB are kept, and
stability under depth D-1 vs D is reported.  A fully rigorous completeness bound
for a *cusped* group needs a horoball refinement (parabolic powers A^k have
displacement ~ 2 log k, so the naive word-depth completeness test is not usable);
this is stated as a caveat, not silently asserted.
"""

from math import cosh, sinh, acosh, log, sqrt, pi, atan2
from pathlib import Path
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib import animation

OUT = Path(__file__).resolve().parent

# ---------------------------------------------------------------- group data
# p = basepoint in H^2
P = 1j
TAU = 2.0 * pi

# Γ(2) generators (SL(2,Z) integer matrices [a,b,c,d]); lowercase = inverse.
GENS = {
    "A": (1, 2, 0, 1),   # z -> z + 2   (fixes ∞)
    "a": (1, -2, 0, 1),  # A^{-1}
    "B": (1, 0, 2, 1),   # z -> z/(2z+1) (fixes 0)
    "b": (1, 0, -2, 1),  # B^{-1}
}
INV = {"A": "a", "a": "A", "B": "b", "b": "B"}


def matmul(X, Y):
    a, b, c, d = X
    e, f, g, h = Y
    return (a * e + b * g, a * f + b * h, c * e + d * g, c * f + d * h)


def minv(M):
    a, b, c, d = M
    return (d, -b, -c, a)


def mob(M, z):
    a, b, c, d = M
    return (a * z + b) / (c * z + d)


def hypdist(z, w):
    """Hyperbolic distance on the upper half plane."""
    return acosh(1.0 + abs(z - w) ** 2 / (2.0 * z.imag * w.imag))


def disp(M, p=P):
    """d(p, γp) for matrix M (a float)."""
    return hypdist(p, mob(M, p))


# ---------------------------------------------------------------- enumeration
def enumerate_words(max_depth, ub):
    """BFS over reduced words in A,B; return (word, matrix, disp) with disp <= ub,
    plus a list of min-disp-per-depth (for the stability report)."""
    kept = []
    per_depth_min = []
    cur = [(g, GENS[g], g) for g in GENS]
    for _d in range(1, max_depth + 1):
        depth_min = float("inf")
        nxt = []
        for (word, M, last) in cur:
            dd = disp(M)
            if dd < depth_min:
                depth_min = dd
            if dd <= ub:
                kept.append((word, M, dd))
            for g in GENS:
                if g != INV[last]:
                    nxt.append((word + g, matmul(M, GENS[g]), g))
        per_depth_min.append(depth_min)
        cur = nxt
        if depth_min > ub + 3.0:   # generous early exit; full depth reached below
            break
    return kept, per_depth_min


def circle_at(z0, t):
    """Hyperbolic circle of radius t centered at z0 -> Euclidean (center, radius)."""
    return complex(z0.real, z0.imag * cosh(t)), z0.imag * sinh(t)


def circle_intersect(c1, r1, c2, r2, tol=1e-9):
    d = abs(c2 - c1)
    if d < tol or d > r1 + r2 or d < abs(r1 - r2):
        return []
    a_ = (r1 * r1 - r2 * r2 + d * d) / (2.0 * d)
    h2 = r1 * r1 - a_ * a_
    h = sqrt(max(0.0, h2))
    mid = c1 + a_ * (c2 - c1) / d
    e = (c2 - c1) / d
    off = 1j * h * e
    return [mid + off, mid - off]


# ---------------------------------------------------------------- folding
def fold_matrices(words):
    """Identity prepended; list of matrices for nearest-translate folding."""
    return [(1, 0, 0, 1)] + [M for (_w, M, _d) in words]


def fold_indices(zpts, mats):
    """For each point, index of the matrix sending it nearest to p (0 = identity)."""
    a = np.array([m[0] for m in mats], dtype=float)
    b = np.array([m[1] for m in mats], dtype=float)
    c = np.array([m[2] for m in mats], dtype=float)
    d = np.array([m[3] for m in mats], dtype=float)
    z = np.asarray(zpts, dtype=complex)
    w = (a[:, None] * z[None, :] + b[:, None]) / (c[:, None] * z[None, :] + d[:, None])
    # hyperbolic distance to p=i, vectorized (keep only points with Im>0)
    num = np.abs(w - P) ** 2
    den = 2.0 * P.imag * w.imag
    dd = np.arccosh(1.0 + num / np.maximum(den, 1e-12))
    dd = np.where(np.isfinite(dd), dd, np.inf)
    return np.argmin(dd, axis=0)


def fold_points(zpts, mats):
    a = np.array([m[0] for m in mats], dtype=float)
    b = np.array([m[1] for m in mats], dtype=float)
    c = np.array([m[2] for m in mats], dtype=float)
    d = np.array([m[3] for m in mats], dtype=float)
    z = np.asarray(zpts, dtype=complex)
    w = (a[:, None] * z[None, :] + b[:, None]) / (c[:, None] * z[None, :] + d[:, None])
    num = np.abs(w - P) ** 2
    den = 2.0 * P.imag * w.imag
    dd = np.arccosh(1.0 + num / np.maximum(den, 1e-12))
    dd = np.where(np.isfinite(dd), dd, np.inf)
    idx = np.argmin(dd, axis=0)
    return w[idx, np.arange(len(z))], idx


# ---------------------------------------------------------------- crossings
def crossings_at(t, words):
    """Crossings of C_t. words = [(word, matrix, disp)] with disp < 2t (oriented).
    Returns list of dicts {word, theta1, theta2, q}."""
    R = 2.0 * t
    c1, r1 = circle_at(P, t)
    seen = set()
    out = []
    for (word, M, dd) in words:
        if dd >= R:
            continue
        key = min(M, minv(M))     # canonical unoriented representative
        if key in seen:
            continue
        seen.add(key)
        q0 = mob(minv(M), P)      # γ^{-1} p
        c2, r2 = circle_at(q0, t)
        for z in circle_intersect(c1, r1, c2, r2):
            if z.imag <= 1e-9:
                continue
            gz = mob(M, z)
            th1 = atan2((z - c1).imag, (z - c1).real) % TAU
            th2 = atan2((gz - c1).imag, (gz - c1).real) % TAU
            out.append({"word": word, "theta1": th1, "theta2": th2, "z": z, "M": M})
    return out


def gauss_word(t, words):
    cs = crossings_at(t, words)
    ev = []
    for i, c in enumerate(cs):
        ev.append((c["theta1"], i))
        ev.append((c["theta2"], i))
    ev.sort()
    return [i for _, i in ev]


def N_exact(t, words):
    R = 2.0 * t
    return sum(1 for (_w, _M, dd) in words if dd < R)


# ---------------------------------------------------------------- drawing
def _draw_frame(ax_cover, ax_fold, t, words, mats):
    c1, r1 = circle_at(P, t)
    th = np.linspace(0.0, TAU, 1600, endpoint=False)
    circ = c1 + r1 * np.exp(1j * th)
    cs = crossings_at(t, words)

    # ---- left: universal cover H (circles colliding) ----
    ax_cover.clear()
    ax_cover.set_aspect("equal")
    ax_cover.plot([-10, 10], [0, 0], color="0.55", lw=0.8)   # real axis (boundary)
    # basepoint and nearest image points ("other fires")
    cusp_words = sorted(words, key=lambda x: x[2])[:40]
    for (_w, M, dd) in cusp_words:
        if dd < 2 * t + 1.2:
            q = mob(M, P)
            ax_cover.plot([q.real], [q.imag], ".", color="#d62728", ms=2.2)
            # a few colliding wavefronts
            if dd < 2 * t:
                c2, r2 = circle_at(q, t)
                tt = np.linspace(0, TAU, 400)
                ax_cover.plot((c2 + r2 * np.exp(1j * tt)).real,
                              (c2 + r2 * np.exp(1j * tt)).imag,
                              color="0.75", lw=0.5, zorder=1)
    ax_cover.plot([P.real], [P.imag], "o", color="#d62728", ms=4, zorder=3)
    ax_cover.plot(circ.real, circ.imag, color="#1f77b4", lw=1.3, zorder=2)
    for c in cs:
        ax_cover.plot([c["z"].real], [c["z"].imag], "x", color="#ff7f0e", ms=4, zorder=4)
    ax_cover.set_xlim(-3.5, 3.5)
    ax_cover.set_ylim(0.02, 7.5)
    ax_cover.set_title(f"cover $\\mathbb{{H}}$: $\\Sigma_t$ and its $\\Gamma(2)$ fires, $t={t:.2f}$",
                       fontsize=9)

    # ---- right: surface (folded into the Dirichlet domain) ----
    ax_fold.clear()
    ax_fold.set_aspect("equal")
    ax_fold.plot([-10, 10], [0, 0], color="0.55", lw=0.8)
    # cusp markers (the three Γ(2)-cusps are 0, 1, ∞)
    for cx in (0, 1):
        ax_fold.plot([cx], [0], "k^", ms=4)
    # fold the wavefront by runs of equal nearest-translate index
    _w, idx = fold_points(circ, mats)
    # split into contiguous runs of equal idx to avoid spurious cross-domain edges
    idx = np.asarray(idx)
    bounds = np.where(np.diff(idx) != 0)[0] + 1
    for seg in np.split(np.arange(len(circ)), bounds):
        ax_fold.plot(_w[seg].real, _w[seg].imag, color="#1f77b4", lw=0.9, zorder=2)
    ax_fold.plot([P.real], [P.imag], "o", color="#d62728", ms=4, zorder=3)
    if cs:
        qs, qi = fold_points(np.array([c["z"] for c in cs]), mats)
        ax_fold.plot(qs.real, qs.imag, "x", color="#ff7f0e", ms=4, zorder=4)
    ax_fold.set_xlim(-1.6, 1.6)
    ax_fold.set_ylim(0.02, 3.6)
    ax_fold.set_title(f"surface: $C_t$ folded, $N(t)={N_exact(t, words)}$", fontsize=9)


def make_snapshots(words, mats):
    fig, axes = plt.subplots(1, 2, figsize=(10.4, 5.0))
    for t in (0.5, 0.95, 1.25, 1.6):
        _draw_frame(axes[0], axes[1], t, words, mats)
        fig.suptitle(f"fire-front twist on $\\mathbb{{H}}^2/\\Gamma(2)$  (t = {t:.2f})",
                     fontsize=11)
        fig.tight_layout(rect=[0, 0, 1, 0.96])
        tag = f"{t:.2f}".replace(".", "_")
        fname = OUT / f"048-fire-front-twist-t{tag}.png"
        fig.savefig(fname, dpi=110)
        print("wrote", fname.name)
    plt.close(fig)


def make_nt_staircase(words, tmax):
    ev = sorted(words, key=lambda x: x[2])
    t_plot = np.linspace(0.0, tmax, 2500)
    N = np.array([N_exact(t, words) for t in t_plot])
    fig, ax = plt.subplots(figsize=(10, 4.6))
    ax.plot(t_plot, N, color="#1f77b4", lw=1.4)
    shown = 0
    for (word, _M, dd) in ev:
        te = dd / 2.0
        if te <= tmax and shown < 60:
            ax.axvline(te, color="#d62728", lw=0.5, ls=":", alpha=0.7)
            ax.text(te, N_exact(te + 1e-9, words) + 0.5, word, rotation=90,
                    fontsize=6, ha="right", va="bottom", color="#d62728")
            shown += 1
    ax.set_xlabel("t (fire time)")
    ax.set_ylabel(r"$N(t)$ = # self-intersections of $C_t$")
    ax.set_title(r"$N(t)=\#\{\gamma\neq e : d(p,\gamma p)<2t\}$ on "
                 "the thrice-punctured sphere")
    ax.grid(alpha=0.3)
    fig.tight_layout()
    fname = OUT / "048-fire-front-twist-nt.png"
    fig.savefig(fname, dpi=120)
    print("wrote", fname.name, f"({shown} events labelled)")
    plt.close(fig)


def make_movie(words, mats):
    fig, axes = plt.subplots(1, 2, figsize=(10.4, 5.0))
    tvals = np.linspace(0.15, 1.7, 70)

    def frame(i):
        t = tvals[i]
        _draw_frame(axes[0], axes[1], t, words, mats)
        fig.suptitle(f"fire-front twist on $\\mathbb{{H}}^2/\\Gamma(2)$  (t = {t:.2f})",
                     fontsize=11)
        fig.tight_layout(rect=[0, 0, 1, 0.96])
        return []

    ani = animation.FuncAnimation(fig, frame, frames=len(tvals), interval=90,
                                  blit=False)
    fname = OUT / "048-fire-front-twist.gif"
    ani.save(fname, writer=animation.PillowWriter(fps=11), dpi=100)
    print("wrote", fname.name)
    plt.close(fig)


def main():
    TMAX = 2.2
    UB = 2.0 * TMAX + 0.6          # keep a margin for stability check
    DEPTH = 12
    words, per_depth_min = enumerate_words(DEPTH, UB)
    words.sort(key=lambda x: x[2])
    print("Γ(2) = <A: z->z+2, B: z->z/(2z+1)>, basepoint p = i")
    print("generator displacements: " +
          ", ".join(f"|{g}|={disp(GENS[g]):.4f}" for g in ("A", "a", "B", "b")))
    print(f"enumerated reduced words (depth {DEPTH}, disp <= {UB:.2f}): {len(words)}")
    print("min displacement per depth:", [f"{m:.3f}" for m in per_depth_min])

    # --- self-checks ---
    mats = fold_matrices(words)
    for t in (0.5, 0.95, 1.25, 1.6, 2.05):
        cs = crossings_at(t, words)
        assert len(cs) == N_exact(t, words), (t, len(cs), N_exact(t, words))
        for c in cs:
            # both preimages z and γz lie on the wavefront Σ_t(p) at distance t
            gz = mob(c["M"], c["z"])
            assert abs(hypdist(P, c["z"]) - t) < 1e-8, (t, "z")
            assert abs(hypdist(P, gz) - t) < 1e-8, (t, "γz")
    print("self-check OK: len(crossings_at) == N_exact; every crossing pair "
          "{z, γz} lies on Σ_t(p) at distance t")
    # stability check: re-enumerate one depth less and compare the spectrum below 2*TMAX
    words2, _ = enumerate_words(DEPTH - 1, UB)
    spec1 = sorted((w, round(d, 9)) for (w, _M, d) in words if d < 2 * TMAX)
    spec2 = sorted((w, round(d, 9)) for (w, _M, d) in words2 if d < 2 * TMAX)
    print(f"stability (depth {DEPTH} vs {DEPTH-1}, disp < {2*TMAX:.2f}): "
          f"{'STABLE' if spec1 == spec2 else 'NOT STABLE'} "
          f"(#={len(spec1)})")

    print("\nevent table (t = ||γ||/2), first 24:")
    for (word, _M, dd) in words[:24]:
        print(f"  t = {dd/2:6.4f}   ||γ|| = {dd:6.4f}   γ = {word}")

    print("\nN(t):")
    for t in (0.5, 0.89, 0.95, 1.2, 1.5, 1.8, 2.1):
        print(f"  t={t:.2f}  N={N_exact(t, words)}")

    print("\nGauss words:")
    for t in (0.95, 1.25, 1.6):
        print(f"  t={t:.2f}  N={N_exact(t, words):2d}  word={gauss_word(t, words)}")

    print("\norbit growth (# γ with ||γ|| <= R):")
    for R in (1.0, 2.0, 3.0, 4.0, 4.4):
        c = sum(1 for (_w, _M, d) in words if d <= R)
        print(f"  R={R:.1f}  count={c}")

    make_snapshots(words, mats)
    make_nt_staircase(words, TMAX)
    make_movie(words, mats)


if __name__ == "__main__":
    main()
