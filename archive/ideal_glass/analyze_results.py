#!/usr/bin/env python3
from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd


def ols_fit(df: pd.DataFrame, y_col: str, x_cols: list[str]) -> pd.DataFrame:
    sub = df[[y_col] + x_cols].dropna()
    if len(sub) < len(x_cols) + 2:
        return pd.DataFrame({"term": ["intercept"] + x_cols, "coef": [np.nan] * (len(x_cols) + 1)})
    y = sub[y_col].to_numpy(dtype=float)
    X = sub[x_cols].to_numpy(dtype=float)
    X = np.column_stack([np.ones(len(X)), X])
    beta, *_ = np.linalg.lstsq(X, y, rcond=None)
    return pd.DataFrame({"term": ["intercept"] + x_cols, "coef": beta})


def matched_differences(df: pd.DataFrame, protocol_a: str, protocol_b: str, metrics: list[str]) -> pd.DataFrame:
    a = df[df["protocol"] == protocol_a][["N", "seed"] + metrics].copy()
    b = df[df["protocol"] == protocol_b][["N", "seed"] + metrics].copy()
    merged = a.merge(b, on=["N", "seed"], suffixes=(f"_{protocol_a}", f"_{protocol_b}"))
    out = merged[["N", "seed"]].copy()
    for m in metrics:
        out[f"delta_{m}_{protocol_b}_minus_{protocol_a}"] = merged[f"{m}_{protocol_b}"] - merged[f"{m}_{protocol_a}"]
    return out


def finite_size_summary(df: pd.DataFrame, metrics: list[str]) -> pd.DataFrame:
    grouped = df.groupby(["protocol", "N"], as_index=False)[metrics].mean(numeric_only=True)
    rows = []
    for protocol, sub in grouped.groupby("protocol"):
        row = {"protocol": protocol}
        for m in metrics:
            fit = sub[["N", m]].dropna()
            if len(fit) >= 2:
                x = 1.0 / fit["N"].to_numpy(dtype=float)
                y = fit[m].to_numpy(dtype=float)
                slope, intercept = np.polyfit(x, y, 1)
                row[f"{m}_Ninf_intercept"] = intercept
                row[f"{m}_invN_slope"] = slope
            else:
                row[f"{m}_Ninf_intercept"] = np.nan
                row[f"{m}_invN_slope"] = np.nan
        rows.append(row)
    return pd.DataFrame(rows)


def build_report(df: pd.DataFrame, outdir: Path) -> None:
    metrics_pair = ["a_G", "a_C", "phi_J", "K0", "G0", "chi_tilde_small_k", "tau_disc"]
    matched_p4_p3 = matched_differences(df, "P3", "P4", metrics_pair)
    matched_p4_p3.to_csv(outdir / "matched_P4_minus_P3.csv", index=False)

    matched_p2_p1 = matched_differences(df, "P1", "P2", metrics_pair)
    matched_p2_p1.to_csv(outdir / "matched_P2_minus_P1.csv", index=False)

    size_metrics = ["a_G", "a_C", "tau_disc", "phi_J", "K0", "G0", "chi_tilde_small_k", "tau_tr"]
    fs = finite_size_summary(df, size_metrics)
    fs.to_csv(outdir / "finite_size_summary.csv", index=False)

    x_cols = ["a_G", "a_C", "tau_disc", "psi6_abs_mean", "tau_tr"]
    outcome_cols = ["phi_J", "K0", "G0", "chi_tilde_small_k", "T_m_proxy", "phi_m_proxy"]
    coef_rows = []
    for y_col in outcome_cols:
        coef_df = ols_fit(df, y_col, x_cols)
        coef_df.insert(0, "outcome", y_col)
        coef_rows.append(coef_df)
    reg = pd.concat(coef_rows, ignore_index=True)
    reg.to_csv(outdir / "regressions.csv", index=False)

    protocol_means = df.groupby("protocol", as_index=False).mean(numeric_only=True)
    protocol_means.to_csv(outdir / "protocol_means.csv", index=False)

    lines = []
    lines.append("# AEG ideal-glass prototype analysis\n")
    lines.append("## Protocol means\n")
    lines.append(protocol_means.to_markdown(index=False))
    lines.append("\n\n## Mean paired differences: P4 - P3\n")
    lines.append(matched_p4_p3.mean(numeric_only=True).to_frame("mean").to_markdown())
    lines.append("\n\n## Mean paired differences: P2 - P1\n")
    lines.append(matched_p2_p1.mean(numeric_only=True).to_frame("mean").to_markdown())
    lines.append("\n\n## Finite-size extrapolation summary\n")
    lines.append(fs.to_markdown(index=False))
    lines.append("\n\n## Regression coefficients\n")
    lines.append(reg.to_markdown(index=False))
    (outdir / "analysis_report.md").write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description="Post-analysis for AEG ideal-glass prototype runs")
    parser.add_argument("--summary", type=str, required=True, help="Path to summary.csv generated by run_experiments.py")
    parser.add_argument("--outdir", type=str, default=None)
    args = parser.parse_args()

    summary_path = Path(args.summary)
    outdir = Path(args.outdir) if args.outdir is not None else summary_path.parent / "analysis"
    outdir.mkdir(parents=True, exist_ok=True)

    import pandas.errors as pe

    if not summary_path.exists():
        raise SystemExit(f"summary file not found: {summary_path}")

    if summary_path.stat().st_size == 0:
        raise SystemExit(
            f"summary file is empty: {summary_path}\n"
            f"Please inspect per-case error files under: {summary_path.parent}"
        )

    try:
        df = pd.read_csv(summary_path)
    except pe.EmptyDataError:
        raise SystemExit(
            f"summary file has no rows/columns: {summary_path}\n"
            f"Please inspect per-case error files under: {summary_path.parent}"
        )

    if df.empty:
        raise SystemExit(
            f"summary dataframe is empty: {summary_path}\n"
            f"Please inspect per-case error files under: {summary_path.parent}"
        )

    build_report(df, outdir)
    print(f"Saved analysis artifacts to: {outdir}")


if __name__ == "__main__":
    main()
